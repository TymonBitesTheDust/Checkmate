const { chromium } = require('/opt/node-tools/node_modules/playwright');
const path = require('path');
const assert = require('assert');
const url = 'file://' + path.resolve(__dirname, '../web/dist/Checkmate.html');
(async () => {
  const b = await chromium.launch();
  const p = await (await b.newContext({ viewport: { width: 1280, height: 1400 } })).newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(url);
  await p.waitForSelector('.view-title');
  const add = async (t) => { await p.keyboard.press('q'); await p.waitForSelector('.modal.quick .editor-title'); await p.keyboard.type(t); await p.keyboard.press('Enter'); await p.waitForTimeout(100); };
  await add('One #Chores'); await add('Two #Chores'); await add('Three #Chores');
  await p.click('a.nav-item:has-text("Chores")');
  await p.waitForSelector('.task-row:has-text("Three")');
  const titles = async () => p.$$eval('.zone .task-row .task-title', (els) => els.map((e) => e.textContent));
  console.log('before', await titles());
  // drag "Three" above "One" using the grip
  const three = await p.$('.task-row:has-text("Three")');
  await three.hover();
  const g = await (await three.$('.grip')).boundingBox();
  const one = await (await p.$('.task-row:has-text("One")')).boundingBox();
  await p.mouse.move(g.x + g.width / 2, g.y + g.height / 2);
  await p.mouse.down();
  await p.mouse.move(g.x + 10, one.y + 20, { steps: 8 });
  await p.mouse.move(g.x + 10, one.y + 8, { steps: 4 });
  await p.mouse.up();
  await p.waitForTimeout(200);
  const after = await titles();
  console.log('after ', after);
  assert.deepStrictEqual(after, ['Three', 'One', 'Two']);
  // add a section and drag into it on the board
  await p.click('button[aria-label="Project actions"]');
  await p.click('.menu-item:has-text("Add section")');
  await p.fill('.modal.dialog input', 'Later');
  await p.click('.modal.dialog button[type="submit"]');
  await p.click('button[aria-label="Board layout"]');
  await p.waitForSelector('.board-col .col-title:has-text("Later")');
  const src = await (await p.$('.board .task-row:has-text("Two")')).boundingBox();
  const col = await (await p.$('.board-col:has(.col-title:has-text("Later")) .col-body')).boundingBox();
  // cards have no grip: use the row's long-press path is touch-only, so drag via the list instead
  await p.click('button[aria-label="List layout"]');
  const two = await p.$('.task-row:has-text("Two")');
  await two.hover();
  const g2 = await (await two.$('.grip')).boundingBox();
  const zone = await (await p.$('.group .zone .add-row')).boundingBox();
  await p.mouse.move(g2.x + 5, g2.y + 5); await p.mouse.down();
  await p.mouse.move(zone.x + 100, zone.y + zone.height / 2, { steps: 10 });
  await p.mouse.up();
  await p.waitForTimeout(200);
  const inLater = await p.$$eval('.group .zone .task-row .task-title', (els) => els.map((e) => e.textContent));
  console.log('in Later', inLater);
  assert.deepStrictEqual(inLater, ['Two']);
  // recurring completion moves the date forward
  await add('Water plants every day');
  await p.goto(url + '#/today');
  await p.waitForSelector('.task-row:has-text("Water plants")');
  await p.click('.task-row:has-text("Water plants") .check');
  await p.waitForTimeout(700);
  const toast = await p.textContent('.toast:last-child .toast-msg');
  console.log('toast:', toast);
  assert(/Next due tomorrow/.test(toast));
  // upcoming: drag tomorrow's task to the day after
  await p.goto(url + '#/upcoming');
  await p.waitForTimeout(300);
  const days = await p.$$('section.day');
  const row = await p.$('section.day >> nth=1 >> .task-row:has-text("Water plants")');
  await row.hover();
  const g3 = await (await row.$('.grip')).boundingBox();
  await p.mouse.move(g3.x + 5, g3.y + 5); await p.mouse.down();
  await p.mouse.move(g3.x + 5, g3.y + 15, { steps: 3 });
  const target = await (await days[2].$('.day-zone')).boundingBox();
  await p.mouse.move(target.x + 50, target.y + 10, { steps: 12 });
  await p.mouse.up();
  await p.waitForTimeout(300);
  console.log('due now', await p.evaluate(() => Object.values(JSON.parse(localStorage.getItem('tickwise.db.v1'))).filter((x) => x.title === 'Water plants').map((x) => x.due && x.due.date)));
  const day3 = await days[2].$$eval('.task-title', (els) => els.map((e) => e.textContent));
  console.log('day after tomorrow:', day3);
  assert(day3.includes('Water plants'));
  console.log(errs.length ? 'ERRORS ' + errs.join('\n') : 'no page errors');
  await b.close();
})().catch((e) => { console.error('FAILED', e.message); process.exit(1); });
