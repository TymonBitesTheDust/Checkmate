// Shared walk-through for a style: picks it in Settings, then screenshots the main
// screens in light and dark, on a computer and a phone, in English and Chinese.
const { chromium } = require('/opt/node-tools/node_modules/playwright');
const path = require('path');
const url = 'file://' + path.resolve(__dirname, '../web/dist/Checkmate.html');

module.exports = async function tour(skin, cardName, OUT) {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1280, height: 820 } });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  p.on('console', (m) => m.type() === 'error' && errs.push('console: ' + m.text()));
  await p.goto(url);
  await p.waitForSelector('.view-title');
  const add = async (t) => { await p.keyboard.press('q'); await p.waitForSelector('.modal.quick .editor-title'); await p.keyboard.type(t); await p.keyboard.press('Enter'); await p.waitForTimeout(80); };
  for (const t of ['Ride to Valentine today 9am p1 #Errands', 'Buy supplies today p2 @town', 'Brush the horse every friday #Errands', 'Write to Mary tomorrow p3 #Errands', 'Mend the fence today', 'Pay the debt yesterday']) await add(t);
  // finish two so the tally and stats have something to show
  await p.click('.task-row:has-text("Pay the debt") .check');
  await p.waitForTimeout(900);
  await p.click('.sb-foot .nav-item');
  await p.click('.settings-tabs button[data-tab="theme"]');
  await p.waitForSelector('.skin-card');
  await p.click(`.skin-card:has-text("${cardName}")`);
  await p.waitForTimeout(400);
  await p.screenshot({ path: `${OUT}/${skin}-1-settings.png` });
  await p.keyboard.press('Escape');
  await p.goto(url + '#/today');
  await p.waitForTimeout(900);
  await p.screenshot({ path: `${OUT}/${skin}-2-today.png` });
  await p.hover('.task-row:has-text("Buy supplies")');
  await p.waitForTimeout(250);
  await p.screenshot({ path: `${OUT}/${skin}-2a-hover.png` });
  await p.click('.task-row:has-text("Mend the fence") .check');
  await p.waitForTimeout(190);
  await p.screenshot({ path: `${OUT}/${skin}-2b-done.png` });
  await p.waitForTimeout(800);
  await p.click('.task-row:has-text("Buy supplies") button[aria-label="Task actions"]');
  await p.waitForTimeout(200);
  await p.screenshot({ path: `${OUT}/${skin}-3-menu.png` });
  await p.keyboard.press('Escape');
  await p.click('a.nav-item:has-text("Upcoming")');
  await p.waitForTimeout(130);
  await p.screenshot({ path: `${OUT}/${skin}-4a-wipe.png` });
  await p.waitForTimeout(700);
  await p.screenshot({ path: `${OUT}/${skin}-4-upcoming.png` });
  await p.click('a.nav-item:has-text("Errands")');
  await p.waitForTimeout(600);
  await p.click('.task-row .task-title');
  await p.waitForTimeout(350);
  await p.screenshot({ path: `${OUT}/${skin}-5-detail.png` });
  await p.click('.modal.detail .side-btn >> nth=0');
  await p.waitForTimeout(250);
  await p.screenshot({ path: `${OUT}/${skin}-5b-due.png` });
  await p.keyboard.press('Escape');
  await p.keyboard.press('Escape');
  await p.click('button[aria-label="Board layout"]');
  await p.waitForTimeout(300);
  await p.screenshot({ path: `${OUT}/${skin}-6-board.png` });
  await p.click('button[aria-label="List layout"]');
  await p.keyboard.press('q');
  await p.keyboard.type('Hunt for a legendary bear next week p2 @hunting');
  await p.waitForTimeout(150);
  await p.screenshot({ path: `${OUT}/${skin}-7-quick.png` });
  await p.keyboard.press('Escape');
  await p.goto(url + '#/productivity');
  await p.waitForTimeout(700);
  await p.screenshot({ path: `${OUT}/${skin}-7b-prod.png` });
  await p.goto(url + '#/search');
  await p.waitForTimeout(500);
  await p.click('.search-box input');
  await p.keyboard.type('horse');
  await p.waitForTimeout(300);
  await p.screenshot({ path: `${OUT}/${skin}-7c-search.png` });
  await p.emulateMedia({ colorScheme: 'dark' });
  await p.goto(url + '#/today');
  await p.waitForTimeout(900);
  await p.screenshot({ path: `${OUT}/${skin}-8-dark.png` });
  await p.hover('.task-row:has-text("Buy supplies")');
  await p.waitForTimeout(250);
  await p.click('.task-row:has-text("Ride to Valentine") .check');
  await p.waitForTimeout(190);
  await p.screenshot({ path: `${OUT}/${skin}-8b-dark-done.png` });
  await p.waitForTimeout(900);
  await p.click('.sb-foot .nav-item');
  await p.waitForSelector('.settings-panel');
  await p.waitForTimeout(300);
  await p.screenshot({ path: `${OUT}/${skin}-8c-dark-settings.png` });
  await p.keyboard.press('Escape');
  await p.click('a.nav-item:has-text("Errands")');
  await p.waitForTimeout(700);
  await p.screenshot({ path: `${OUT}/${skin}-8d-dark-project.png` });
  // Chinese
  await p.evaluate(() => { const k = 'tickwise.prefs.v1'; const v = JSON.parse(localStorage.getItem(k)); v.language = 'zh-Hant'; localStorage.setItem(k, JSON.stringify(v)); });
  await p.emulateMedia({ colorScheme: 'light' });
  await p.goto(url + '#/today');
  await p.reload();
  await p.waitForTimeout(900);
  await p.screenshot({ path: `${OUT}/${skin}-9-zh.png` });
  await p.click('.task-row:has-text("Buy supplies") .check');
  await p.waitForTimeout(190);
  await p.screenshot({ path: `${OUT}/${skin}-9b-zh-done.png` });
  await p.waitForTimeout(800);
  // Phone
  const m = await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
  const mp = await m.newPage();
  mp.on('pageerror', (e) => errs.push('phone: ' + e.message));
  await mp.goto(url);
  await mp.evaluate((s) => localStorage.setItem('tickwise.prefs.v1', JSON.stringify({ skin: s, theme: 'light', language: 'en' })), skin);
  await mp.reload();
  await mp.waitForTimeout(800);
  await mp.screenshot({ path: `${OUT}/${skin}-10-phone.png` });
  await mp.click('.topbar .icon-btn');
  await mp.waitForTimeout(450);
  await mp.screenshot({ path: `${OUT}/${skin}-11-phone-menu.png` });
  await mp.evaluate((s) => localStorage.setItem('tickwise.prefs.v1', JSON.stringify({ skin: s, theme: 'dark', language: 'en' })), skin);
  await mp.reload();
  await mp.waitForTimeout(800);
  await mp.screenshot({ path: `${OUT}/${skin}-12-phone-dark.png` });
  const overflow = await mp.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
  if (overflow) errs.push('phone layout scrolls sideways');
  await b.close();
  return errs;
};
